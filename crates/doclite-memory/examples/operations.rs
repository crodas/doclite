//! The storage layer with nothing above it: operations built as values, run
//! against an engine.
//!
//! This is what `doclite`'s derive generates calls to. Read it if you are
//! writing an engine, or if you want the primitives without a record type.
//!
//! ```sh
//! cargo run -p doclite-memory --example operations
//! ```

use doclite_core::{
    all, between, bounded, exact, key, prefix, AbortCode, Bound, Db, Index, ObjectId, Operation,
    Outcome, Query, StorageError,
};
use doclite_memory::MemoryEngine;

static BY_EMAIL: Index<1> = Index::new("users_by_email");
static BY_CITY_AGE: Index<3> = Index::new("users_by_city_age");

const DUPLICATE_EMAIL: AbortCode = AbortCode::new(100);
const NOT_ENOUGH: AbortCode = AbortCode::new(101);

#[tokio::main]
async fn main() -> Result<(), StorageError> {
    let db = Db::open(
        MemoryEngine::new(),
        &[BY_EMAIL.schema(), BY_CITY_AGE.schema()],
    )
    .await?;

    let file = |id: ObjectId, email: &'static str, city: &'static str, age: u8| {
        Operation::new()
            .require_absent(&BY_EMAIL, exact(key![email]), DUPLICATE_EMAIL)
            .put_object(id, format!("{email} in {city}").into_bytes())
            .put_index(&BY_EMAIL, key![email], id)
            .put_index(&BY_CITY_AGE, key![city, age, id], id)
            .returning(id)
    };

    println!("an operation is a value, so it can be looked at before it runs:");
    let first = file(ObjectId(1), "ana@example.py", "Asuncion", 31);
    println!(
        "  {} steps, mutates: {}",
        first.steps().len(),
        first.mutates()
    );
    println!("  well formed: {:?}", first.check(db.schemas()).is_ok());

    println!("\nrunning it, then running the very same value again:");
    println!("  {:?}", db.run(&first).await?);
    println!("  {:?}", db.run(&first).await?);
    println!("  the second is an answer, not an error: the precondition held its ground");

    for (id, email, city, age) in [
        (2u64, "bruno@example.py", "Asuncion", 44),
        (3, "carla@example.py", "Asuncion", 25),
        (4, "diego@example.ar", "Cordoba", 38),
    ] {
        db.run(&file(ObjectId(id), email, city, age)).await?;
    }

    println!("\nscanning a prefix of a compound index:");
    for row in scan(&db, prefix::<3, 1>(key!["Asuncion"])).await? {
        println!("  {:?}", String::from_utf8_lossy(&row.1));
    }

    println!("\na closed range on the second column:");
    let range = between::<3, 2>(
        key!["Asuncion", 30u8],
        key!["Asuncion", 45u8],
        Bound::Incl,
        Bound::Excl,
    );
    for row in scan(&db, range).await? {
        println!("  {:?}", String::from_utf8_lossy(&row.1));
    }

    println!("\nan open endpoint needs no maximum for the column type,");
    println!("but it also does not stop at the end of the group:");
    let open = bounded::<3, 2>(Some((key!["Asuncion", 40u8], Bound::Incl)), None);
    for row in scan(&db, open).await? {
        println!("  {:?}", String::from_utf8_lossy(&row.1));
    }
    println!("  Cordoba is in there because >= (Asuncion, 40) means exactly that:");
    println!("  everything at or after that point in the index, city included.");

    println!("\nto stay inside one city, name it on both endpoints:");
    let inside = bounded::<3, 2>(
        Some((key!["Asuncion", 40u8], Bound::Incl)),
        Some((key!["Asuncion", u8::MAX], Bound::Incl)),
    );
    for row in scan(&db, inside).await? {
        println!("  {:?}", String::from_utf8_lossy(&row.1));
    }
    println!("  both endpoints are the same width, so the city pins the group and");
    println!("  the age ranges within it. `doclite`'s generated by_city_age does");
    println!("  exactly this, which is why a compound query there stays in range.");

    println!("\ntwo reads from one view of the store:");
    let both = Query::zip(
        Query::count(&BY_EMAIL, all()),
        Query::object::<Vec<u8>>(ObjectId(1)),
    );
    if let Outcome::Committed((count, object)) = db.run(&both).await? {
        println!(
            "  {count} users, and #1 is {:?}",
            object.as_deref().map(String::from_utf8_lossy)
        );
    }

    println!("\na precondition placed after a mutation sees it:");
    let sees_itself = Operation::new()
        .put_index(&BY_EMAIL, key!["elena@example.py"], ObjectId(9))
        .require_count(&BY_EMAIL, exact(key!["elena@example.py"]), 1, NOT_ENOUGH);
    println!("  {:?}", db.run(&sees_itself).await?);

    println!("\nand a refused operation stages nothing:");
    let refused = Operation::new()
        .put_index(&BY_EMAIL, key!["frida@example.py"], ObjectId(10))
        .require_count(&BY_EMAIL, exact(key!["frida@example.py"]), 2, NOT_ENOUGH);
    println!("  {:?}", db.run(&refused).await?);
    println!(
        "  frida is still absent: {:?}",
        db.run(&Query::count(&BY_EMAIL, exact(key!["frida@example.py"])))
            .await?
    );

    println!("\none template, instantiated once per scanned row:");
    let cascade = Operation::new().for_each(
        Query::scan(&BY_CITY_AGE, prefix::<3, 1>(key!["Cordoba"])).limit(100),
        |row| Operation::new().delete_index(&BY_EMAIL, exact(key![row.key(0)])),
    );
    println!("  {:?}", db.run(&cascade).await?);
    println!("  the body ran once at build time, against a symbolic row");

    Ok(())
}

/// Every row of a range, with the object each one names.
async fn scan<const K: usize>(
    db: &Db<MemoryEngine>,
    range: doclite_core::Range<3, K>,
) -> Result<Vec<(doclite_core::Row, Vec<u8>)>, StorageError> {
    let query = Query::scan(&BY_CITY_AGE, range)
        .limit(100)
        .with_objects::<Vec<u8>>();
    match db.run(&query).await? {
        Outcome::Committed(rows) => Ok(rows),
        Outcome::Aborted(code) => {
            println!("  the scan aborted: {code}");
            Ok(Vec::new())
        }
    }
}
